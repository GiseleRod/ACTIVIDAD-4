package grupo1.ejercicio1;

public class ResultadoExtremo {

    private final int valor;
    private final int posicion;

    public ResultadoExtremo(int valor, int posicion) {
        this.valor = valor;
        this.posicion = posicion;
    }

    public int getValor() {
        return valor;
    }

    public int getPosicion() {
        return posicion;
    }
}
